#!/usr/bin/env python3
"""Write dsp/elements_tables.lib from the tables dumped by `build/dump tables`.

Every table is the one Elements' firmware uses (elements/resources.cc,
stmlib/dsp/units.cc), read back from the compiled reference, not recomputed:
the floats are printed with 17 significant digits, the exact value of each
float32 (a double-precision program reads the very float, a single-precision
one rounds it back to itself), and the samples are the int16 values
themselves.

    python3 scripts/gen_tables.py build/tables dsp/elements_tables.lib

Run by `make tables`, after `./build/dump tables build/tables`.

Inputs, in the directory given first (written by ref/dump.cpp, `dump_tables`):

- `lut_NAME.txt` for each float table of FLOAT_TABLES: one value per line, `%.17g`;
- `NAME.txt` for each integer table of INT_TABLES: one integer per line (the int16
  samples, and the sample boundaries as unsigned offsets);
- `lcg_jump.txt`: 49 lines `A C`, the k-step coefficients of stmlib::Random for
  k = 0 .. 48, as signed 32-bit integers;
- `constants.txt`: lines `NAME VALUE`, the float32 constants and unsigned 32-bit
  thresholds the C++ computes at run time.

Output: the Faust library given second, overwritten. Every table becomes a size,
a reading function and a `waveform`; the constants become plain definitions.
"""

import sys
from pathlib import Path

# The float tables, in the order they are written: the name without its `lut_`
# prefix (the dump's file is `lut_NAME.txt`, the Faust table `lut_NAME`) and the
# one-line description written above it in the library.
FLOAT_TABLES = [
    ("approx_svf_gain", "pulse amplitude of the strike exciters (`Exciter::GetPulseAmplitude`)"),
    ("approx_svf_g", "exciter filter cutoff, `tan(pi f)`, 32 Hz to 16 kHz"),
    ("approx_svf_r", "exciter filter damping, Q from 0.5 to 500"),
    ("approx_svf_h", "exciter filter normalisation `1 / (1 + 2 g + g^2)`"),
    ("4_decades", "`10^(4 x)`, the Q of the modal resonator"),
    ("accent_gain_coarse", "strength: coarse gain, 3 dB/V"),
    ("accent_gain_fine", "strength: fine gain"),
    ("stiffness", "inharmonicity of the modes as a function of geometry"),
    ("env_increments", "envelope phase increment per block as a function of time"),
    ("env_linear", "envelope shape: linear"),
    ("env_expo", "envelope shape: exponential"),
    ("env_quartic", "envelope shape: `t^3.32`"),
    ("midi_to_f_high", "MIDI note + 48 to frequency / 32000"),
    ("midi_to_f_low", "fraction of a semitone in 1/256 to a ratio"),
    ("svf_shift", "delay of the string's damping filter, in periods"),
    ("pitch_ratio_high", "stmlib: semitones + 128 to a ratio"),
    ("pitch_ratio_low", "stmlib: fraction of a semitone in 1/256 to a ratio"),
]

# The integer tables: the name of the dump's file (`NAME.txt`) and of the Faust
# table, and its description.
INT_TABLES = [
    ("smp_sample_data", "the nine mallet and hit samples of the strike exciter, back to back"),
    ("smp_noise_sample", "the noise sample of the blow exciter's granular player"),
    ("smp_boundaries", "start of each strike sample in `smp_sample_data`"),
]


def wrap(values, per_line=12):
    """Lay out the elements of a `waveform` over several lines.

    values: the values as strings, already formatted.
    per_line: how many values go on one line.
    Returns the lines, each indented by four spaces, joined by ",\\n": a
    comma-separated list to place between the braces of `waveform{...}`.
    """
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ",".join(values[i:i + per_line]))
    return ",\n".join(lines)


def main():
    """Read the dumped tables from argv[1] and write the Faust library argv[2].

    The values are copied as text, never parsed into floats, so that the 17 digits
    the dump printed reach the library unchanged; only the 32-bit thresholds of
    constants.txt are parsed, to be written as signed integers.
    """
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    out = []
    # The header of the generated library.
    out.append("//############################# elements_tables.lib ####################################")
    out.append("// Generated by scripts/gen_tables.py from the tables of Mutable Instruments Elements")
    out.append("// (elements/resources.cc and stmlib/dsp/units.cc, Emilie Gillet, MIT license),")
    out.append("// read back from the compiled reference `build/dump tables`. Do not edit.")
    out.append("//")
    out.append("// Each table `NAME` is a pair: `NAME_size`, its length, and `NAME(i)`, its value at")
    out.append("// integer index `i`, read with `rdtable`.")
    out.append("//########################################################################################")
    out.append("")
    out.append('declare name "elements_tables";')
    out.append('declare license "MIT";')
    out.append("")
    # Each float table: its size, a reader that truncates the index to an integer as
    # the C++'s array subscripts do, and the waveform itself, 12 values per line.
    for name, what in FLOAT_TABLES:
        values = (src / f"lut_{name}.txt").read_text().split()
        out.append(f"// lut_{name}: {what}.")
        out.append(f"lut_{name}_size = {len(values)};")
        out.append(f"lut_{name}(i) = rdtable(lut_{name}_wf, int(i));")
        out.append(f"lut_{name}_wf = waveform{{\n{wrap(values)}\n}};")
        out.append("")
    # The integer tables, the same way; their values are shorter, 20 per line.
    for name, what in INT_TABLES:
        values = (src / f"{name}.txt").read_text().split()
        out.append(f"// {name}: {what}.")
        out.append(f"{name}_size = {len(values)};")
        out.append(f"{name}(i) = rdtable({name}_wf, int(i));")
        out.append(f"{name}_wf = waveform{{\n{wrap(values, 20)}\n}};")
        out.append("")
    # The k-step jumps of the random generator: one line `A C` per k, split into two
    # tables indexed by k. They let the model hand each consumer of a block the word
    # it would draw without running the generator k times.
    jumps = [l.split() for l in (src / "lcg_jump.txt").read_text().splitlines()]
    out.append("// stmlib::Random advanced k steps: s -> lcg_a(k) * s + lcg_c(k) (mod 2^32), k = 0 .. 48,")
    out.append("// as signed 32-bit integers.")
    out.append(f"lcg_size = {len(jumps)};")
    out.append("lcg_a(k) = rdtable(lcg_a_wf, int(k));")
    out.append("lcg_c(k) = rdtable(lcg_c_wf, int(k));")
    out.append(f"lcg_a_wf = waveform{{\n{wrap([a for a, _ in jumps], 8)}\n}};")
    out.append(f"lcg_c_wf = waveform{{\n{wrap([c for _, c in jumps], 8)}\n}};")
    out.append("")
    out.append("// Constants computed in float32 by the C++ (ref/dump.cpp: the expressions of exciter.cc")
    out.append("// and string.cc). The probabilities are unsigned 32-bit thresholds, given here as the")
    out.append("// signed integers with the same bits.")
    for line in (src / "constants.txt").read_text().splitlines():
        name, value = line.split()
        # The float constants are copied as printed, at 17 digits: the reverb LFOs'
        # coefficients are so close to 2 that one ulp changes their frequency by 2 %.
        if name in ("string_delay0", "reverb_lfo1_coef", "reverb_lfo2_coef"):
            out.append(f"{name} = {value};")
        else:
            # An unsigned 32-bit value (a probability threshold, the generator's seed)
            # as the signed 32-bit integer with the same bits: Faust's integers are
            # signed, and the model's unsigned comparisons flip the sign bit.
            v = int(value)
            out.append(f"{name} = {v - (1 << 32) if v >= (1 << 31) else v};")
    out.append("")
    dst.write_text("\n".join(out))


if __name__ == "__main__":
    main()
